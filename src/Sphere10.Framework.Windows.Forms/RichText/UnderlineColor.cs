namespace Sphere10.Framework.Windows.Forms;

/// <summary>
/// Specifies the color of underline that should be
/// applied to the text.
/// </summary>
public enum UnderlineColor {
	/// <summary>Black.</summary>
	Black = 0x00,

	/// <summary>Blue.</summary>
	Blue = 0x10,

	/// <summary>Cyan.</summary>
	Cyan = 0x20,

	/// <summary>Lime green.</summary>
	LimeGreen = 0x30,

	/// <summary>Magenta.</summary>
	Magenta = 0x40,

	/// <summary>Red.</summary>
	Red = 0x50,

	/// <summary>Yellow.</summary>
	Yellow = 0x60,

	/// <summary>White.</summary>
	White = 0x70,

	/// <summary>DarkBlue.</summary>
	DarkBlue = 0x80,

	/// <summary>DarkCyan.</summary>
	DarkCyan = 0x90,

	/// <summary>Green.</summary>
	Green = 0xA0,

	/// <summary>Dark magenta.</summary>
	DarkMagenta = 0xB0,

	/// <summary>Brown.</summary>
	Brown = 0xC0,

	/// <summary>Olive green.</summary>
	OliveGreen = 0xD0,

	/// <summary>Dark gray.</summary>
	DarkGray = 0xE0,

	/// <summary>Gray.</summary>
	Gray = 0xF0
}
