using System;
using System.Collections.Generic;
using System.IO;

// ReSharper disable CheckNamespace

namespace Sphere10.Framework;

/// <summary>
/// Maps file extensions to MIME types (see https://www.iana.org/assignments/media-types/media-types.xhtml). The table is generated by
/// scripts/generate-mime-types.py from mime-db (https://github.com/jshttp/mime-db, MIT licence, Copyright (c) 2014 Jonathan Ong and
/// Douglas Christopher Wilson), which combines the IANA registry with the Apache and nginx type maps. It is embedded compressed, as
/// Resources.MimeTypes, and read into memory on the first lookup only, so code that never looks up a MIME type pays nothing for it.
/// </summary>
public static class MimeHelper {
	private const string GenericMimeType = "application/octet-stream";
	private static readonly IFuture<IReadOnlyDictionary<string, string>> _mimeTypes = Tools.Values.Future.SynchronizedLazyLoad<IReadOnlyDictionary<string, string>>(ReadMimeTypes);

	/// <summary>The MIME type for a file extension, such as "png" or ".png". An unknown extension maps to application/octet-stream.</summary>
	public static bool TryGetMimeTypeFromFileExt(string fileExt, out string mimeType) {
		if (string.IsNullOrWhiteSpace(fileExt)) {
			mimeType = default;
			return false;
		}
		mimeType = _mimeTypes.Value.TryGetValue("." + fileExt.TrimStart('.').ToLowerInvariant(), out var known) ? known : GenericMimeType;
		return true;
	}

	// The resource is gzip-compressed text: each line is an extension, a tab and its MIME type.
	private static IReadOnlyDictionary<string, string> ReadMimeTypes() {
		using var table = new MemoryStream();
		using (var resource = new MemoryStream(Resources.MimeTypes, false))
			Tools.Streams.GZipDecompress(resource, table);
		table.Position = 0;
		using var reader = new StreamReader(table);
		var mimeTypes = new Dictionary<string, string>(StringComparer.Ordinal);
		while (reader.ReadLine() is { } line) {
			var separator = line.IndexOf('\t');
			if (separator > 0)
				mimeTypes[line[..separator]] = line[(separator + 1)..];
		}
		return mimeTypes;
	}
}
